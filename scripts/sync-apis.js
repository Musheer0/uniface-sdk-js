import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import "dotenv/config";
import openapiTS, { astToString } from "openapi-typescript";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT_PATH = path.resolve(__dirname, "../src/types/blurfield-api.d.ts");

// No built-in default: pass the deployment URL explicitly or via env so no
// endpoint is baked into the repo. Keep in sync with README.md.

function printUsage() {
  console.log(`Regenerate TypeScript types from the Blurfield OpenAPI spec.

Usage:
  node scripts/sync-apis.js [url] [options]
  npm run sync-api -- [url] [options]

Arguments:
  url                  API base URL (positional, optional if set via env).

Options:
  --url <url>          Same as the positional argument.
  -h, --help           Show this message.

Resolution order: --url flag > positional arg > BLURFIELD_BASE_URL >
BACKEND_API_URL. One of them is required.

Examples:
  npm run sync-api -- https://your-deployment.example.com
  BLURFIELD_BASE_URL=https://your-deployment.example.com npm run sync-api
`);
}

function parseBaseUrl(argv) {
  if (argv.includes("--help") || argv.includes("-h")) {
    printUsage();
    process.exit(0);
  }

  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--url" && argv[i + 1]) return argv[i + 1];
    const match = argv[i].match(/^--url=(.+)$/);
    if (match) return match[1];
  }

  const positional = argv.find((arg) => !arg.startsWith("-"));
  if (positional) return positional;

  return process.env.BLURFIELD_BASE_URL || process.env.BACKEND_API_URL;
}

async function main() {
  const rawBaseUrl = parseBaseUrl(process.argv.slice(2));
  if (!rawBaseUrl) {
    console.error("Error: API base URL is required.");
    printUsage();
    process.exit(1);
  }
  const baseUrl = rawBaseUrl.replace(/\/+$/, "");

  const openApiUrl = `${baseUrl}/openapi.json`;
  console.log(`Fetching OpenAPI spec from: ${openApiUrl}`);

  const ast = await openapiTS(new URL(openApiUrl));
  const contents = astToString(ast);

  // Ensure output directory exists
  const outputDir = path.dirname(OUTPUT_PATH);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  // Add header comment
  const header = `/**
 * This file is auto-generated by scripts/sync-apis.js
 * Do not edit manually. Run \`npm run sync-api\` to regenerate.
 *
 * Generated from: ${openApiUrl}
 * Generated at: ${new Date().toISOString()}
 */
`;

  fs.writeFileSync(OUTPUT_PATH, header + contents);
  console.log(`Types written to: ${OUTPUT_PATH}`);
}

main().catch((err) => {
  console.error("Failed to sync API types:", err);
  process.exit(1);
});
